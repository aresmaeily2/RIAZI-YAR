/// متن‌های استاندارد حریم خصوصی — منبع واحد برای صفحه والدین و تنظیمات
/// تا هیچ‌جا ادعای ناسازگار مطرح نشود.
///
/// ممیزی ۱.۰.۲ (یافته حریم خصوصی): نسخه قبل در تنظیمات ادعای
/// «همه داده‌ها فقط روی همین گوشی ذخیره می‌شوند» را بدون شرط مطرح می‌کرد
/// در حالی که «راهنمای آنلاین» (اختیاری، پیش‌فرض خاموش) در صورت
/// فعال‌سازی داده‌های لازم پرسش راهنما را به سرور پیکربندی‌شده
/// ارسال می‌کند. اکنون:
///  • ادعای «محلی» فقط برای حالت واقعاً محلی مطرح می‌شود و اشاره صریح
///    دارد که فعال‌سازی آنلاین این وضعیت را تغییر می‌دهد.
///  • در حالت آنلاین، مقصد و نوع داده ارسالی صریحاً توضیح داده می‌شود.
///  • فعال‌سازی آنلاین تنها با اقدام آگاهانه والد (دیالوگ رضایت) انجام
///    می‌شود — در main.dart.
///
/// ممیزی ۱.۰.۳ (دستورکار P1-۵): متن‌ها دقیقاً با payload واقعی درخواست
/// راهنما (lib/core/guide/ai_guide_http.dart) هماهنگ شدند. فیلدهای دقیق
/// JSON ارسالی و هیچ چیز بیشتر:
///   utterance، prompt، hints، wrongStreak، activityType، lessonId
///  • هدف ارسال: تولید پیام راهنما برای همان پرسش
///  • دریافت‌کننده: فقط سروری که والد پیکربندی کرده است
///  • نگهداری: سیاست نگهداری سمت سرور خارج از کنترل اپ است و صادقانه
///    همین گفته می‌شود؛ اپ هیچ داده اضافی (نام، شناسه دستگاه، تاریخچه،
///    موقعیت) ارسال نمی‌کند.
///  • خاموش‌کردن: کلید «راهنمای آنلاین» در صفحه والدین — با خاموشی هیچ
///    درخواستی ارسال نمی‌شود و داده‌ها محلی می‌مانند.
class PrivacyTexts {
  /// فیلدهای دقیق payload راهنمای آنلاین — منبع واحد برای دیالوگ رضایت
  /// و متن‌ها (ممیزی ۱.۰.۳). با jsonEncode در ai_guide_http.dart یکی است.
  static const onlineGuidePayloadFields = <String, String>{
    'utterance':
        'متن گفتار کودک حداکثر ۱۲۰ نویسه — فقط اگر ورود گفتاری استفاده شود؛ در غیر این صورت رشته خالی',
    'prompt': 'متن پرسش فعلی',
    'hints': 'فهرست راهنماهای همان پرسش (بدون گفتن پاسخ)',
    'wrongStreak': 'تعداد پاسخ‌های اشتباه پیاپی کودک در همان پرسش',
    'activityType': 'نوع فعالیت آموزشی (مثل countAndChoose یا matchCount)',
    'lessonId': 'شناسه فعالیت درسی که پرسش از آن است',
  };

  /// فهرست متنی فیلدها برای نمایش در دیالوگ/متن‌ها.
  static String get onlineGuidePayloadList {
    final lines = <String>[];
    onlineGuidePayloadFields.forEach((key, desc) {
      lines.add('• $key — $desc');
    });
    return lines.join('\n');
  }

  /// پیام ذخیره‌سازی در حالت پیش‌فرض (راهنمای آنلاین خاموش).
  static const storageNoticeLocal =
      'ذخیره‌سازی داده‌ها (وضعیت فعلی: محلی): همه تلاش‌ها و پیشرفت‌ها فقط '
      'روی حافظه همین دستگاه ذخیره می‌شوند و هیچ داده‌ای به هیچ سروری '
      'ارسال نمی‌شود. اگر «راهنمای آنلاین» را روشن کنید، این وضعیت تغییر '
      'می‌کند و توضیح کامل آن پیش از فعال‌سازی نمایش داده می‌شود.';

  /// پیام ذخیره‌سازی در حالت راهنمای آنلاین روشن (ممیزی ۱.۰.۳ — هماهنگ
  /// با payload واقعی: فقط شش فیلد اعلام‌شده ارسال می‌شود).
  static const storageNoticeOnline =
      'ذخیره‌سازی داده‌ها (وضعیت فعلی: راهنمای آنلاین روشن است): پیشرفت و '
      'تلاش‌ها همچنان فقط روی همین دستگاه ذخیره می‌شوند؛ اما هنگام درخواست '
      'راهنما، فقط این شش فیلد به سروری که والد پیکربندی کرده ارسال '
      'می‌شود: utterance (متن گفتار کودک حداکثر ۱۲۰ نویسه، در صورت استفاده '
      'از ورود گفتاری)، prompt (متن پرسش)، hints (راهنماهای پرسش)، '
      'wrongStreak (تعداد اشتباه پیاپی)، activityType (نوع فعالیت) و '
      'lessonId (شناسه فعالیت درسی). هدف، تولید پیام راهنما برای همان '
      'پرسش است. نام، عکس، شناسه دستگاه، موقعیت و تاریخچه کودک ارسال '
      'نمی‌شود. سیاست نگهداری داده سمت سرور به پیکربندی آن سرور بستگی '
      'دارد و در کنترل این اپ نیست. با خاموش‌کردن «راهنمای آنلاین» در '
      'صفحه والدین، هیچ داده‌ای دیگر ارسال نمی‌شود.';

  /// انتخاب متن ذخیره‌سازی بر اساس وضعیت واقعی راهنمای آنلاین.
  /// (ممیزی ۱.۰.۲ — نقطه تصمیم واحد و تست‌پذیر)
  static String storageNoticeFor(bool onlineGuideEnabled) =>
      onlineGuideEnabled ? storageNoticeOnline : storageNoticeLocal;

  /// توضیح کوتاه برای کارت «درباره» در تنظیمات (ممیزی ۱.۰.۳ — هماهنگ با
  /// payload واقعی).
  static const aboutPrivacyBlock =
      '• پیش‌فرض این اپ کاملاً محلی است: همه تلاش‌ها و پیشرفت‌ها فقط روی '
      'همین گوشی ذخیره می‌شوند و هیچ داده‌ای ارسال نمی‌شود.\n'
      '• هیچ اطلاعات شخصی از کودک گرفته نمی‌شود و ثبت‌نامی وجود ندارد.\n'
      '• راهنمای آموزشی به‌صورت محلی (روی همین گوشی) کار می‌کند.\n'
      '• استثنا: اگر والد «راهنمای آنلاین» را در بخش والدین آگاهانه و با '
      'تأیید صریح فعال کند، هنگام درخواست راهنما فقط این شش فیلد به '
      'سرور پیکربندی‌شده ارسال می‌شود: utterance، prompt، hints، '
      'wrongStreak، activityType، lessonId (هدف: تولید پیام راهنما برای '
      'همان پرسش). داده اضافی، نام یا اطلاعات شخصی کودک ارسال نمی‌شود؛ '
      'توضیح کامل و آدرس سرور پیش از فعال‌سازی نمایش داده می‌شود و با '
      'خاموش‌کردن همان کلید، ارسال داده قطع می‌شود. در این نسخه آدرس '
      'سرور به‌صورت پیش‌فرض در اپ تعبیه نشده است.\n'
      '• پیشرفت و تاریخچه تلاش‌ها همیشه فقط روی همین گوشی می‌ماند.';
}
